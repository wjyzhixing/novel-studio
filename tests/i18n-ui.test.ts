import { readFile } from 'node:fs/promises'
import { describe, expect, it } from 'vitest'

describe('i18n shell integration', () => {
  it('persists an independent UI locale and exposes a keyboard-friendly selector', async () => {
    const app = await readFile(new URL('../src/renderer/src/App.tsx', import.meta.url), 'utf8')
    const css = await readFile(new URL('../src/renderer/src/styles/app.css', import.meta.url), 'utf8')
    const welcome = await readFile(new URL('../src/renderer/src/components/Welcome.tsx', import.meta.url), 'utf8')
    const sidebar = await readFile(new URL('../src/renderer/src/components/Sidebar.tsx', import.meta.url), 'utf8')
    const bottomPanel = await readFile(new URL('../src/renderer/src/components/BottomPanel.tsx', import.meta.url), 'utf8')
    const healthPanel = await readFile(new URL('../src/renderer/src/components/ProjectHealthPanel.tsx', import.meta.url), 'utf8')
    const rightPanel = await readFile(new URL('../src/renderer/src/components/RightPanel.tsx', import.meta.url), 'utf8')
    expect(app).toContain('aria-label={uiText(\'uiLanguage\')}')
    expect(app).toContain("value=\"en-US\">{uiText('languageEnglish')}")
    expect(welcome).toContain("useUiText()")
    expect(sidebar).toContain("useUiText()")
    expect(bottomPanel).toContain("import { useUiText } from '../lib/i18n'")
    expect(bottomPanel).toContain("uiText('openChat')")
    expect(bottomPanel).toContain("uiText('saveNote')")
    expect(healthPanel).toContain("useUiText")
    expect(healthPanel).toContain("uiText('projectIntegrity')")
    expect(healthPanel).toContain("uiText('databaseSchema')")
    expect(healthPanel).toContain("uiText('latestRepair')")
    expect(healthPanel).toContain("uiText('repairIndexes')")
    expect(rightPanel).toContain("import { useUiText } from '../lib/i18n'")
    expect(rightPanel).toContain("uiText('chatCancelled')")
    expect(rightPanel).toContain("uiText('openStandaloneChat')")
    expect(rightPanel).toContain("uiText('runWorkflow')")
    expect(rightPanel).toContain("uiText('statusRunning')")
    expect(rightPanel).toContain('statusLabel(workflowRun.status)')
    expect(rightPanel).toContain("uiText('providerRequired')")
    expect(rightPanel).toContain("uiText('suggestionAccepted')")
    expect(rightPanel).toContain("uiText('inspectContext')")
    expect(rightPanel).toContain("uiText('collapseAll')")
    expect(css).toContain('.ui-language-control select:hover')
    expect(css).toContain('.ui-language-control select:focus-visible')
  })
})
